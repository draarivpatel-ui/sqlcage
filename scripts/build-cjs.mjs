import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'src', 'index.mjs');
const targetPath = path.join(root, 'dist', 'index.cjs');
const checkMode = process.argv.includes('--check');
const source = await readFile(sourcePath, 'utf8');

const EXPORT_NAMES = [
  'SQLCAGE_VERSION',
  'DIALECTS',
  'CODE',
  'SqlCageError',
  'sql',
  'isSqlFragment',
  'compileQuery',
  'createSqlCage',
  'isValidIdentifier',
  'quoteIdentifier',
  'safeColumns',
  'safeOrderBy',
  'safeLimitOffset',
  'createSchemaGuard',
  'sqlJoin',
  'sqlAnd',
  'sqlOr',
  'sqlIn',
  'sqlValues',
  'sqlSet',
  'escapeLikePattern',
  'sqlLike',
  'auditSqlQuery'
];

let body = source;
body = body.replace(/^export const /gm, 'const ');
body = body.replace(/^export class /gm, 'class ');
body = body.replace(/^export function /gm, 'function ');
if (!body.includes('export default sqlcage;')) {
  throw new Error('CJS transform could not find the default export');
}
body = body.replace('export default sqlcage;', '');
if (/^import\s/m.test(body)) throw new Error('CJS transform left an import declaration behind');
if (/^export\s/m.test(body)) throw new Error('CJS transform left an export declaration behind');

for (const name of EXPORT_NAMES) {
  const declaration = new RegExp('(?:const|class|function) ' + name + '\\b');
  if (!declaration.test(body)) {
    throw new Error('CJS transform could not find declaration for ' + name);
  }
}

const output = [
  "'use strict';",
  '',
  '/* Generated by scripts/build-cjs.mjs from src/index.mjs. Do not edit directly. */',
  '',
  body.trim(),
  '',
  'module.exports = {',
  ...EXPORT_NAMES.map((name) => '  ' + name + ','),
  '};',
  '',
  'module.exports.default = sqlcage;',
  ''
].join('\n');

if (checkMode) {
  let existing = '';
  try {
    existing = await readFile(targetPath, 'utf8');
  } catch {
    existing = '';
  }
  if (existing !== output) {
    throw new Error('dist/index.cjs is not up to date; run node scripts/build-cjs.mjs');
  }
  process.stdout.write('dist/index.cjs is up to date\n');
} else {
  await mkdir(path.dirname(targetPath), { recursive: true });
  await writeFile(targetPath, output, 'utf8');
  process.stdout.write('dist/index.cjs generated from src/index.mjs\n');
}
