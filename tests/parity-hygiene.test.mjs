function readRepoFile(relativePath) {
  return fs.readFileSync(path.join(root, relativePath), 'utf8');
}

function walk(directory, output = []) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (entry.name === '.git' || entry.name === 'node_modules' || entry.name === 'coverage') continue;
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) walk(fullPath, output);
    else if (entry.isFile()) output.push(fullPath);
  }
  return output;
}

const repoFiles = walk(root).map((file) => path.relative(root, file)).sort();

test('CJS and ESM expose the same named function surface', () => {
  const names = [
    'SQLCAGE_VERSION', 'DIALECTS', 'CODE', 'SqlCageError', 'sql', 'isSqlFragment', 'compileQuery',
    'createSqlCage', 'isValidIdentifier', 'quoteIdentifier', 'safeColumns', 'safeOrderBy', 'safeLimitOffset',
    'createSchemaGuard', 'sqlJoin', 'sqlAnd', 'sqlOr', 'sqlIn', 'sqlValues', 'sqlSet', 'escapeLikePattern',
    'sqlLike', 'auditSqlQuery'
  ];
  for (const name of names) {
    assert.equal(typeof cjs[name], typeof esm[name], name);
  }
  assert.deepEqual(Object.keys(cjs).sort(), [...names, 'default'].sort());
});

test('CJS default export is the aggregate object', () => {
  assert.equal(typeof cjs.default.sql, 'function');
  assert.equal(typeof cjs.default.compileQuery, 'function');
  assert.equal(cjs.default.CODE, cjs.CODE);
});

test('CJS tagged-template compilation matches ESM for postgres', () => {
  const fragment = cjs.sql`SELECT * FROM users WHERE id = ${42} AND name = ${'x'}`;
  assert.deepEqual(cjs.compileQuery(fragment), esm.compileQuery(esm.sql`SELECT * FROM users WHERE id = ${42} AND name = ${'x'}`));
});

test('CJS tagged-template compilation matches ESM for mysql', () => {
  const fragment = cjs.sql`SELECT ${1}, ${'x'}`;
  assert.deepEqual(
    cjs.compileQuery(fragment, { dialect: 'mysql' }),
    esm.compileQuery(esm.sql`SELECT ${1}, ${'x'}`, { dialect: 'mysql' })
  );
});

