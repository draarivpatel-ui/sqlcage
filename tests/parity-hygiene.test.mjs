test('CJS schema guard output matches ESM', () => {
  const spec = { users: { columns: ['id', 'email'], sortable: ['id'] } };
  for (const dialect of ['postgres', 'mysql', 'sqlite']) {
    const cjsGuard = cjs.createSchemaGuard(spec, { dialect });
    const esmGuard = esm.createSchemaGuard(spec, { dialect });
    const cjsSql = cjs.compileQuery(cjs.sql`SELECT ${cjsGuard.column('users', 'id')} FROM ${cjsGuard.table('users')}`, { dialect });
    const esmSql = esm.compileQuery(esm.sql`SELECT ${esmGuard.column('users', 'id')} FROM ${esmGuard.table('users')}`, { dialect });
    assert.deepEqual(cjsSql, esmSql);
  }
});

test('CJS helper output matches ESM for injection-shaped strings', () => {
  const hostile = "x'); DROP TABLE users; --";
  const cjsResult = cjs.compileQuery(cjs.sql`WHERE id ${cjs.sqlIn([hostile])} AND name = ${hostile}`);
  const esmResult = esm.compileQuery(esm.sql`WHERE id ${esm.sqlIn([hostile])} AND name = ${hostile}`);
  assert.deepEqual(cjsResult, esmResult);
  assert.equal(cjsResult.text.includes(hostile), false);
});

test('CJS audit output matches ESM audit output', () => {
  assert.deepEqual(cjs.auditSqlQuery('SELECT 1; DROP TABLE x'), esm.auditSqlQuery('SELECT 1; DROP TABLE x'));
});

test('CJS fragment forgery rejection matches ESM', () => {
  for (const forged of [{ __sql: 'OR 1=1' }, {}, null, 'SELECT 1']) {
    for (const implementation of [cjs, esm]) {
      assert.throws(() => implementation.compileQuery(forged), (error) => error.code === 'SQLCAGE_INVALID_FRAGMENT');
    }
  }
});

